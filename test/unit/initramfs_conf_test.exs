defmodule NervesSign.InitramfsConfTest do
  use ExUnit.Case, async: true

  alias NervesSign.Initramfs

  # The config-first form: settings declared in the project's target config
  # are rendered into the initramfs.conf cryptinit reads. What matters is
  # that the rendering is exact — these lines decide whether a fleet device
  # can mount its rootfs.

  test "settings render as plain key = value lines, in order" do
    conf =
      Initramfs.render_conf(
        rootfs_key:
          "cmd:/usr/sbin/bootstrap-or-derive --raw /dev/mmcblk0p2 /dev/mmcblk0p4 aes-cbc-plain",
        rootfs_cipher: "aes-cbc-plain"
      )

    assert conf =~
             "rootfs_key = cmd:/usr/sbin/bootstrap-or-derive --raw /dev/mmcblk0p2 /dev/mmcblk0p4 aes-cbc-plain\n"

    assert conf =~ "rootfs_cipher = aes-cbc-plain\n"

    # Key before cipher, as declared.
    [key_at, cipher_at] =
      for line <- ["rootfs_key", "rootfs_cipher"] do
        {at, _} = :binary.match(conf, line)
        at
      end

    assert key_at < cipher_at
  end

  test "the rendered file says where it came from" do
    conf = Initramfs.render_conf(rootfs_cipher: "aes-cbc-plain")
    assert conf =~ "Generated by nerves_sign"
    assert conf =~ "cryptinit"
  end
end
