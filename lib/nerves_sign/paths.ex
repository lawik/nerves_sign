defmodule NervesSign.Paths do
  @moduledoc """
  Resolve the project-owned config paths the pipeline reads.

  Every path in `config :nerves_sign` may be absolute or relative to the
  firmware project (`NERVES_APP`). Files the project is expected to own
  (generated by `mix nerves_sign.gen.<board>`) fall back to the copy shipped in
  nerves_sign's `priv/boards/<board>/` when the project hasn't generated one.
  """

  alias NervesSign.Board

  @doc """
  Absolute path for `path`, relative paths resolved against `base`.

  Raises when `path` is nil: every caller has a required file behind it, and a
  missing config key should say so rather than surface later as a confusing
  fwup or openssl error.
  """
  @spec resolve(Path.t() | nil, Path.t()) :: Path.t()
  def resolve(nil, _base), do: Mix.raise("nerves_sign: missing required path in config")

  def resolve(path, base),
    do: if(Path.type(path) == :absolute, do: path, else: Path.join(base, path))

  @doc "Absolute path to `name` in the board's `priv/boards/<board>/` dir."
  @spec board_file(atom(), Path.t()) :: Path.t()
  def board_file(board, name) do
    Path.join([:code.priv_dir(:nerves_sign), Board.impl(board).priv_dir(), name])
  end

  @doc """
  Resolve a file the project may own.

  An explicit `configured` path wins (resolved against `app_dir`), then the
  generated project copy at `app_dir/project_relative`, then the board default
  shipped in priv.
  """
  @spec project_or_board(atom(), Path.t() | nil, Path.t(), Path.t(), Path.t()) :: Path.t()
  def project_or_board(board, configured, app_dir, project_relative, board_name)

  def project_or_board(_board, configured, app_dir, _project_relative, _board_name)
      when is_binary(configured),
      do: resolve(configured, app_dir)

  def project_or_board(board, nil, app_dir, project_relative, board_name) do
    project = Path.join(app_dir, project_relative)
    if File.exists?(project), do: project, else: board_file(board, board_name)
  end
end
